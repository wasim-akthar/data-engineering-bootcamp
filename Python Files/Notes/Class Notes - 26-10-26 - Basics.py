# print() displays a message or value on the screen.
print('Hello World')

# Variables store values that we can use later in our program.
# Integer values are whole numbers without decimal points.
a = 10
b = 20

# We can perform arithmetic with variables and store the result in a new variable.
# The + operator adds two numbers together.
c = a + b

# The print() function can display text and multiple values.
# In Python, \n creates a new line inside a string.
print("My name is Wasim Akthar.\nI'm becoming a Data Engineer.")

# A string is text enclosed in quotation marks.
print("I studied in Dr. M.G.R Research and Educational Institute")

# Printing a label and a calculation together makes the output easier to understand.
# The + operator adds 25 and 35; the answer is displayed after the comma.
print('25 + 35 = ', 25 + 35)

# The - operator subtracts one number from another.
print('50 - 15 = ', 50 - 15)

# The * operator multiplies two numbers in Python.
print('12 X 5 = ', 12 * 5)

# A string may contain multiple \n escape sequences to print several lines.
print('text - 1\ntest - 2\ntext - 3')